// submitTestMetricReport serves the action: the report is built from the values
// and put on the event stream as an event of the format MetricReport ("generate
// the metric report as an alert event"); it is not added to the collection.
func (b *BMC) submitTestMetricReport(w http.ResponseWriter, in map[string]any) {
	name, _ := in["MetricReportName"].(string)
	if name == "" {
		b.fail(w, http.StatusBadRequest, "", "The action parameter MetricReportName is required.", "Base.1.19.ActionParameterMissing")
		return
	}
	list, ok := in["GeneratedMetricReportValues"].([]any)
	if !ok {
		b.fail(w, http.StatusBadRequest, "", "The action parameter GeneratedMetricReportValues is required.", "Base.1.19.ActionParameterMissing")
		return
	}
	ts := b.now().Format(time.RFC3339)
	vals := []any{}
	for _, x := range list {
		m, ok := x.(map[string]any)
		if _, isStr := m["MetricValue"].(string); !ok || !isStr {
			b.fail(w, http.StatusBadRequest, "", "A value of GeneratedMetricReportValues has no MetricValue string.", "Base.1.19.ActionParameterValueTypeError")
			return
		}
		v := map[string]any{"MetricValue": m["MetricValue"], "Timestamp": ts}
		for _, k := range []string{"MetricId", "MetricProperty", "Timestamp"} {
			if s, ok := m[k]; ok {
				v[k] = s
			}
		}
		vals = append(vals, v)
	}
	b.tel.tests = append(b.tel.tests, in)
	b.publishReport(map[string]any{"@odata.type": reportType, "@odata.id": mrRoot + "/" + name, "Id": name, "Name": name,
		"Timestamp": ts, "MetricValues": vals})
	w.WriteHeader(http.StatusNoContent)
}
