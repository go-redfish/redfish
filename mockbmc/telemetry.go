// installDefinition adds a definition (with the defaults a service gives) and
// its first report.
func (b *BMC) installDefinition(in map[string]any) string {
	id, _ := in["Id"].(string)
	p := mrdRoot + "/" + id
	in["@odata.type"] = "#MetricReportDefinition.v1_4_7.MetricReportDefinition"
	in["Status"] = map[string]any{"State": "Enabled", "Health": "OK"}
	if _, ok := in["MetricReportDefinitionEnabled"]; !ok {
		in["MetricReportDefinitionEnabled"] = true
	}
	if _, ok := in["ReportActions"]; !ok {
		in["ReportActions"] = []any{"LogToMetricReportsCollection"}
	}
	if _, ok := in["ReportUpdates"]; !ok {
		in["ReportUpdates"] = "Overwrite"
	}
	in["MetricReport"] = link(mrRoot + "/" + id)
	b.addMember(mrdRoot, p, in)
	b.generate(p, false)
	return p
}

