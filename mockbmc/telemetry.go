func seconds(s string) (float64, bool) {
	m := durationRE.FindStringSubmatch(s)
	if m == nil || len(s) < 3 || s == "PT" {
		return 0, false
	}
	var total float64
	for i, mult := range map[int]float64{1: 86400, 3: 3600, 4: 60, 5: 1} {
		if m[i] == "" {
			continue
		}
		v, err := strconv.ParseFloat(strings.TrimRight(m[i], "DHMS"), 64)
		if err != nil {
			return 0, false
		}
		total += v * mult
	}
	return total, true
}

func inList(v any, allowed []string) bool {
	s, ok := v.(string)
	return ok && slices.Contains(allowed, s)
}

// createDefinition serves the POST to the MetricReportDefinitions collection.
func (b *BMC) createDefinition(w http.ResponseWriter, in map[string]any) {
	bad := func(msg, id string) {
		b.fail(w, http.StatusBadRequest, "", msg, id)
	}
	notInList := func(prop string, v any) {
		bad(fmt.Sprintf("The value %v for the property %s is not in the list of acceptable values.", v, prop), "Base.1.19.PropertyValueNotInList")
	}
	typ := in["MetricReportDefinitionType"]
	if typ == nil {
		bad("The property MetricReportDefinitionType is a required property and must be included in the request.", "Base.1.19.PropertyMissing")
		return
	}
	if !inList(typ, definitionTypeSet) {
		notInList("MetricReportDefinitionType", typ)
		return
	}
	ms, _ := in["Metrics"].([]any)
	if len(ms) == 0 {
		bad("The property Metrics is a required property and must be included in the request.", "Base.1.19.PropertyMissing")
		return
	}
	for _, x := range ms {
		m, ok := x.(map[string]any)
		if !ok {
			bad("The value in the array Metrics is not an object.", "Base.1.19.PropertyValueTypeError")
			return
		}
		id, hasID := m["MetricId"].(string)
		props, hasProps := m["MetricProperties"].([]any)
		switch {
		case hasID && hasProps, !hasID && !hasProps:
			bad("A metric names a MetricId or MetricProperties, one of them.", "Base.1.19.PropertyValueConflict")
			return
		case hasID && b.res[mdRoot+"/"+id] == nil:
			notInList("MetricId", id)
			return
		}
		for _, p := range props {
			if s, _ := p.(string); !strings.HasPrefix(s, "/redfish/") {
				bad(fmt.Sprintf("The value %v for the property MetricProperties is not in the correct format.", p), "Base.1.19.PropertyValueFormatError")
				return
			}
		}
		if f, ok := m["CollectionFunction"]; ok && !inList(f, []string{"Average", "Maximum", "Minimum", "Summation"}) {
			notInList("CollectionFunction", f)
			return
		}
		if s, ok := m["CollectionTimeScope"]; ok && !inList(s, timeScopeSet) {
			notInList("CollectionTimeScope", s)
			return
		}
		if d, ok := m["CollectionDuration"]; ok {
			if s, _ := d.(string); !func() bool { _, ok := seconds(s); return ok }() {
				bad(fmt.Sprintf("The value %v for the property CollectionDuration is not in the correct format.", d), "Base.1.19.PropertyValueFormatError")
				return
			}
		}
	}
	if _, ok := in["Wildcards"]; ok {
		bad("Wildcards are not supported by this service.", "Base.1.19.GeneralError")
		return
	}
	if sched, _ := in["Schedule"].(map[string]any); sched != nil || typ == "Periodic" {
		ri, _ := sched["RecurrenceInterval"].(string)
		secs, ok := seconds(ri)
		switch {
		case typ == "Periodic" && ri == "":
			bad("The property Schedule is required for a Periodic definition: it needs RecurrenceInterval.", "Base.1.19.PropertyMissing")
			return
		case ri != "" && !ok:
			bad(fmt.Sprintf("The value %v for the property RecurrenceInterval is not in the correct format.", ri), "Base.1.19.PropertyValueFormatError")
			return
		case ri != "" && secs < 1:
			bad(fmt.Sprintf("The value %v for the property RecurrenceInterval is shorter than the MinCollectionInterval.", ri), "Base.1.19.PropertyValueNotInList")
			return
		}
	}
	actions, hasActions := in["ReportActions"].([]any)
	for _, a := range actions {
		if !inList(a, reportActionSet) {
			notInList("ReportActions", a)
			return
		}
	}
	if u, ok := in["ReportUpdates"]; ok && !inList(u, reportUpdateSet) {
		notInList("ReportUpdates", u)
		return
	}
	if lim, ok := in["AppendLimit"].(float64); ok && lim < 0 {
		bad("The value for the property AppendLimit is below its minimum of 0.", "Base.1.19.PropertyValueNotInList")
		return
	}
	if u := in["ReportUpdates"]; (u == "AppendWrapsWhenFull" || u == "AppendStopsWhenFull") && in["AppendLimit"] == nil {
		bad("The property AppendLimit is required with this ReportUpdates.", "Base.1.19.PropertyMissing")
		return
	}
	logs := !hasActions || len(actions) == 0 || slices.Contains(actions, any("LogToMetricReportsCollection"))
	if n := len(b.res[mrRoot]["Members"].([]any)); logs && n >= maxReports {
		bad(fmt.Sprintf("The service holds %d metric reports, its MaxReports.", n), "Base.1.19.GeneralError")
		return
	}
	id, _ := in["Id"].(string)
	if _, given := in["Id"]; given && !defIDRE.MatchString(id) {
		bad(fmt.Sprintf("The value %v for the property Id is not in the correct format.", in["Id"]), "Base.1.19.PropertyValueFormatError")
		return
	}
	if id == "" {
		for n := len(b.res[mrdRoot]["Members"].([]any)) + 1; ; n++ {
			if id = strconv.Itoa(n); b.res[mrdRoot+"/"+id] == nil {
				break
			}
		}
	} else if b.res[mrdRoot+"/"+id] != nil {
		b.fail(w, http.StatusConflict, "", "The resource "+id+" already exists.", "Base.1.19.ResourceAlreadyExists")
		return
	}
	def := map[string]any{"Id": id}
	for _, k := range []string{"Name", "MetricReportDefinitionType", "Schedule", "Metrics", "ReportActions", "ReportUpdates", "AppendLimit",
		"ReportTimespan", "SuppressRepeatedMetricValue", "MetricReportDefinitionEnabled"} {
		if v, ok := in[k]; ok {
			def[k] = v
		}
	}
	if _, ok := def["Name"]; !ok {
		def["Name"] = id
	}
	p := b.installDefinition(def)
	w.Header().Set("Location", p)
	writeJSON(w, http.StatusCreated, b.res[p], etagOf(b.res[p]))
}

// deleteDefinition removes the reports a deleted definition made.
func (b *BMC) deleteDefinition(p string) {
	if b.tel == nil || !strings.HasPrefix(p, mrdRoot+"/") {
		return
	}
	for _, x := range slices.Clone(b.res[mrRoot]["Members"].([]any)) {
		rp := x.(map[string]any)["@odata.id"].(string)
		if l, _ := b.res[rp]["MetricReportDefinition"].(map[string]any); l != nil && l["@odata.id"] == p {
			b.removeReport(rp)
		}
	}
	delete(b.tel.occ, p)
	delete(b.tel.last, p)
}

