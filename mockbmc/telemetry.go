// The TelemetryService of the mock (DSP8010 2025.4: TelemetryService 1.4.1,
// MetricDefinition 1.3.6, MetricReportDefinition 1.4.7, MetricReport 1.5.2,
// Triggers 1.4.0; DSP0266 1.23.0 12.5.2.2). Neither mockup carries the service,
// so augmentTelemetry adds it to both trees:
//
//   - the TelemetryService with its four collections, a SubmitTestMetricReport
//     action (with an ActionInfo that lists its two parameters), the supported
//     collection functions, a MinCollectionInterval of one second and a MaxReports
//     of eight;
//   - three MetricDefinitions (TotalPower, TotalEnergy, CPU1Temp), whose
//     MetricProperties point at the Reading of the sensors of chassis 1U;
//   - two MetricReportDefinitions: PowerMetrics, Periodic every ten seconds,
//     AppendWrapsWhenFull with an AppendLimit of 16, whose reports go to the
//     collection and to the event stream; and CPUTemperature, OnRequest;
//   - one Trigger (an upper critical threshold on TotalPower);
//   - POST to the MetricReportDefinitions collection (400 for what the schema or
//     the service's limits refuse, 409 for an Id in use) and DELETE of a member,
//     which removes the reports it made.
//
// The values of a report are the Reading of the sensors at the time it is
// generated, so a PATCH of a sensor shows in the next report. A report is
// generated when its definition is created (no event), when TickTelemetry is
// called (Periodic, and OnChange when a value changed; with an event on the
// stream when ReportActions has RedfishEvent), and at each GET of the report of
// an OnRequest definition (MetricReportDefinitionType: "generated when an HTTP
// GET is performed on the specified metric report"). There is no timer: a test
// ticks, `redfish mock serve` ticks on an interval. The CollectionFunction of a
// metric is accepted and checked against the supported functions, but the mock
// reports the point value: it keeps no history to average over. Wildcards are
// refused. The mock's clock is Options.Clock.
//
// Over the stream a metric report is an event of the format MetricReport: the
// $filter criterion EventFormatType separates it from the Events, and a stream
// without a filter carries both. The criterion MetricReportDefinition is not
// supported (the EventService says so).

const (
	telRoot    = root + "/TelemetryService"
	mdRoot     = telRoot + "/MetricDefinitions"
	mrdRoot    = telRoot + "/MetricReportDefinitions"
	mrRoot     = telRoot + "/MetricReports"
	trigRoot   = telRoot + "/Triggers"
	reportType = "#MetricReport.v1_5_2.MetricReport"
	maxReports = 8
)

type telState struct {
	occ   map[string]int    // definition -> reports generated by Tick
	last  map[string]string // definition -> signature of the last values (OnChange)
	tests []map[string]any  // SubmitTestMetricReport bodies
	seq   int
}

var (
	supportedFunctions = []any{"Average", "Maximum", "Minimum", "Summation"}
	reportActionSet    = []string{"LogToMetricReportsCollection", "RedfishEvent"}
	reportUpdateSet    = []string{"Overwrite", "AppendWrapsWhenFull", "AppendStopsWhenFull", "NewReport"}
	definitionTypeSet  = []string{"Periodic", "OnChange", "OnRequest"}
	timeScopeSet       = []string{"Point", "Interval", "StartupInterval"}
	durationRE         = regexp.MustCompile(`^P(\d+D)?(T(\d+H)?(\d+M)?(\d+(\.\d+)?S)?)?$`)
	defIDRE            = regexp.MustCompile(`^[A-Za-z0-9._-]{1,128}$`)
)

// TestMetricReports returns the bodies of the SubmitTestMetricReport actions
// accepted so far.
func (b *BMC) TestMetricReports() []map[string]any {
	b.mu.Lock()
	defer b.mu.Unlock()
	return slices.Clone(b.tel.tests)
}

func (b *BMC) now() time.Time {
	if b.opts.Clock != nil {
		return b.opts.Clock.Now().UTC()
	}
	return time.Now().UTC()
}

func link(p string) map[string]any { return map[string]any{"@odata.id": p} }

