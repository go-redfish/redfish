type metricRef struct{ id, prop string }

// refs lists the properties a definition reports: the MetricProperties of the
// MetricDefinition a metric names, or the properties it lists.
func (b *BMC) refs(def map[string]any) []metricRef {
	var out []metricRef
	ms, _ := def["Metrics"].([]any)
	for _, x := range ms {
		m, _ := x.(map[string]any)
		if id, _ := m["MetricId"].(string); id != "" {
			md := b.res[mdRoot+"/"+id]
			ps, _ := md["MetricProperties"].([]any)
			for _, p := range ps {
				if s, _ := p.(string); s != "" {
					out = append(out, metricRef{id, s})
				}
			}
			continue
		}
		ps, _ := m["MetricProperties"].([]any)
		for _, p := range ps {
			if s, _ := p.(string); s != "" {
				out = append(out, metricRef{"", s})
			}
		}
	}
	return out
}

// lookup reads the property a MetricProperties URI names: a resource path and a
// JSON pointer (RFC 6901) after the number sign.
func (b *BMC) lookup(prop string) (any, bool) {
	resPath, frag, _ := strings.Cut(prop, "#")
	var cur any = b.res[clean(resPath)]
	if cur == nil || frag == "" {
		return nil, false
	}
	for _, seg := range strings.Split(strings.TrimPrefix(frag, "/"), "/") {
		seg = strings.ReplaceAll(strings.ReplaceAll(seg, "~1", "/"), "~0", "~")
		switch c := cur.(type) {
		case map[string]any:
			v, ok := c[seg]
			if !ok {
				return nil, false
			}
			cur = v
		case []any:
			i, err := strconv.Atoi(seg)
			if err != nil || i < 0 || i >= len(c) {
				return nil, false
			}
			cur = c[i]
		default:
			return nil, false
		}
	}
	return cur, true
}

// metricString is a value as MetricValue.MetricValue has it (MetricReport 1.5.2:
// a number as its string, a boolean as true or false, an array or object as JSON
// text, null as null).
func metricString(v any) any {
	switch x := v.(type) {
	case nil:
		return nil
	case string:
		return x
	case bool:
		return strconv.FormatBool(x)
	case float64:
		return strconv.FormatFloat(x, 'f', -1, 64)
	case int:
		return strconv.Itoa(x)
	case int64:
		return strconv.FormatInt(x, 10)
	}
	b, _ := json.Marshal(v)
	return string(b)
}

func (b *BMC) sample(def map[string]any, ts string) []any {
	var vals []any
	for _, r := range b.refs(def) {
		v, _ := b.lookup(r.prop)
		m := map[string]any{"MetricProperty": r.prop, "MetricValue": metricString(v), "Timestamp": ts}
		if r.id != "" {
			m["MetricId"] = r.id
		}
		vals = append(vals, m)
	}
	return vals
}

func signature(vals []any) string {
	var sb strings.Builder
	for _, x := range vals {
		m := x.(map[string]any)
		fmt.Fprintf(&sb, "%v=%v;", m["MetricProperty"], m["MetricValue"])
	}
	return sb.String()
}

func cloneJSON(m map[string]any) map[string]any {
	data, _ := json.Marshal(m)
	var out map[string]any
	_ = json.Unmarshal(data, &out)
	return out
}

func disable(def map[string]any) {
	def["MetricReportDefinitionEnabled"] = false
	def["Status"] = map[string]any{"State": "Disabled", "Health": "OK"}
}

// generate makes a report for a definition, as its ReportUpdates says, and
// reports whether it did (AppendStopsWhenFull may refuse). onRequest: the report
// of an OnRequest definition, rewritten in place and never sent as an event.
func (b *BMC) generate(defPath string, publish bool) bool {
	def := b.res[defPath]
	id, _ := def["Id"].(string)
	ts := b.now().Format(time.RFC3339)
	vals := b.sample(def, ts)
	updates, _ := def["ReportUpdates"].(string)
	typ, _ := def["MetricReportDefinitionType"].(string)
	if typ == "OnRequest" {
		updates = "Overwrite"
	}
	reportPath := mrRoot + "/" + id
	if l, _ := def["MetricReport"].(map[string]any); l != nil {
		if s, _ := l["@odata.id"].(string); s != "" {
			reportPath = s
		}
	}
	cur := b.res[reportPath]
	limit := math.MaxInt
	if n, ok := def["AppendLimit"].(int); ok {
		limit = n
	} else if f, ok := def["AppendLimit"].(float64); ok {
		limit = int(f)
	}
	switch updates {
	case "NewReport":
		b.tel.seq++
		reportPath = mrRoot + "/" + id + "_" + b.now().Format("20060102T150405Z") + "_" + strconv.Itoa(b.tel.seq)
		cur = nil
	case "AppendWrapsWhenFull", "AppendStopsWhenFull":
		if cur != nil {
			old, _ := cur["MetricValues"].([]any)
			if updates == "AppendStopsWhenFull" && len(old)+len(vals) > limit {
				disable(def)
				return false
			}
			vals = append(slices.Clone(old), vals...)
			if len(vals) > limit {
				vals = vals[len(vals)-limit:]
			}
		}
	}
	report := map[string]any{"@odata.type": reportType, "Id": path1(reportPath), "Name": id + " metric report",
		"MetricReportDefinition": link(defPath), "Timestamp": ts, "MetricValues": vals}
	if cur != nil {
		cur["Timestamp"], cur["MetricValues"] = ts, vals
	} else {
		b.dropOldestReports(id)
		b.addMember(mrRoot, reportPath, report)
	}
	def["MetricReport"] = link(reportPath)
	if actions, _ := def["ReportActions"].([]any); publish && typ != "OnRequest" && slices.Contains(actions, any("RedfishEvent")) {
		b.publishReport(cloneJSON(b.res[reportPath]))
	}
	return true
}

func path1(p string) string { return p[strings.LastIndexByte(p, '/')+1:] }

// dropOldestReports keeps the collection within MaxReports before a new report
// is added: the oldest report of the definition goes first, else the oldest.
func (b *BMC) dropOldestReports(defID string) {
	for {
		ms, _ := b.res[mrRoot]["Members"].([]any)
		if len(ms) < maxReports {
			return
		}
		victim := ms[0].(map[string]any)["@odata.id"].(string)
		for _, x := range ms {
			if s := x.(map[string]any)["@odata.id"].(string); strings.HasPrefix(path1(s), defID+"_") {
				victim = s
				break
			}
		}
		b.removeReport(victim)
	}
}

func (b *BMC) removeReport(p string) {
	var keep []any
	for _, x := range b.res[mrRoot]["Members"].([]any) {
		if x.(map[string]any)["@odata.id"] != p {
			keep = append(keep, x)
		}
	}
	b.res[mrRoot]["Members"], b.res[mrRoot]["Members@odata.count"] = keep, len(keep)
	delete(b.res, p)
}

// publishReport puts a metric report on the event stream (the stream sends it
// with Context and an id).
func (b *BMC) publishReport(report map[string]any) {
	if b.ev == nil {
		return
	}
	n := b.ev.next + 1
	b.ev.next = n
	b.ev.hist = append(b.ev.hist, histEvent{id: n, report: report})
	if len(b.ev.hist) > maxHist {
		b.ev.hist = b.ev.hist[1:]
	}
	close(b.ev.wake)
	b.ev.wake = make(chan struct{})
}

// TickTelemetry is the passing of time for the telemetry service: it generates a
// report for every enabled Periodic definition, and for every enabled OnChange
// definition whose values changed since its last report, sending the reports
// whose ReportActions say RedfishEvent to the event stream. A Periodic
// definition whose Schedule has MaxOccurrences is disabled once it has made that
// many reports. It returns the number of reports generated.
func (b *BMC) TickTelemetry() int {
	b.mu.Lock()
	defer b.mu.Unlock()
	if b.tel == nil || b.res[mrdRoot] == nil {
		return 0
	}
	n := 0
	ms, _ := b.res[mrdRoot]["Members"].([]any)
	for _, x := range slices.Clone(ms) {
		p := x.(map[string]any)["@odata.id"].(string)
		def := b.res[p]
		if def == nil {
			continue
		}
		if en, ok := def["MetricReportDefinitionEnabled"].(bool); ok && !en {
			continue
		}
		switch def["MetricReportDefinitionType"] {
		case "Periodic":
			if sched, _ := def["Schedule"].(map[string]any); sched != nil {
				if m, ok := sched["MaxOccurrences"].(float64); ok && b.tel.occ[p] >= int(m) {
					disable(def)
					continue
				}
			}
			if b.generate(p, true) {
				b.tel.occ[p]++
				n++
			}
		case "OnChange":
			sig := signature(b.sample(def, ""))
			if sig != b.tel.last[p] {
				b.tel.last[p] = sig
				if b.generate(p, true) {
					n++
				}
			}
		}
	}
	return n
}

// onRequest regenerates the report of an OnRequest definition when it is read.
func (b *BMC) onRequest(p string) {
	if b.tel == nil || !strings.HasPrefix(p, mrRoot+"/") || b.res[p] == nil {
		return
	}
	l, _ := b.res[p]["MetricReportDefinition"].(map[string]any)
	dp, _ := l["@odata.id"].(string)
	if def := b.res[dp]; def != nil && def["MetricReportDefinitionType"] == "OnRequest" {
		b.generate(dp, false)
	}
}

